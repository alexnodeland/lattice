/**
 * Writes the client's types from the packages' committed documents: each REST surface's OpenAPI
 * document through openapi-typescript, each WebSocket protocol's JSON Schema through
 * json-schema-to-typescript, and lattice's integrations, as portalr writes them from lattice-core's
 * registry, as a constant. The drift test calls `generate()` and compares; `moon run
 * client:types` writes. openapi-typescript loads TypeScript 6, this package's own `typescript`
 * (portalr ADR-0010).
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(import.meta.dirname, "..", "..", "..", "..", "..");
const out = join(import.meta.dirname, "..", "src", "generated");

const HEADER =
  "// Generated by scripts/generate.ts from the committed document named below. Don't edit.\n";

const OPENAPI = {
  "artifactr.openapi.ts": "packages/artifactr/schemas/artifactr.openapi.json",
  "files.openapi.ts": "packages/artifactr/schemas/artifactr-files.openapi.json",
  "diagrams.openapi.ts": "packages/artifactr/schemas/artifactr-excalidraw.openapi.json",
  "reflexr.openapi.ts": "packages/reflexr/schemas/reflexr.openapi.json",
  "grantr.openapi.ts": "packages/grantr/schemas/grantr.openapi.json",
  "portalr.openapi.ts": "packages/portalr/schemas/portalr.openapi.json",
  "relayr.openapi.ts": "packages/relayr/schemas/relayr.openapi.json",
} as const;

const SCHEMAS = {
  "artifactr.v1.ts": "packages/artifactr/schemas/artifactr.v1.json",
  "reflexr.v1.ts": "packages/reflexr/schemas/reflexr.v1.json",
  "reflexr.rules.v1.ts": "packages/reflexr/schemas/reflexr.rules.v1.json",
  "artifactr_ui.v1.ts": "packages/artifactr/schemas/artifactr_ui.v1.json",
  "artifactr_excalidraw.v1.ts": "packages/artifactr/schemas/artifactr_excalidraw.v1.json",
} as const;

/** lattice's integrations, each key's default and sentence, in the registry's order (ADR-0045). */
const INTEGRATIONS = "packages/portalr/schemas/integrations.json";

/**
 * The libraries' command catalogs, each written by its package's `schema` task (lattice ADR-0041):
 * every action a person can take in portalr is one of their commands (lattice RFC-0014).
 */
const CATALOGS = [
  "packages/artifactr/schemas/artifactr.commands.json",
  "packages/grantr/schemas/grantr.commands.json",
  "packages/portalr/schemas/portalr.commands.json",
  "packages/reflexr/schemas/reflexr.commands.json",
  "packages/relayr/schemas/relayr.commands.json",
] as const;

/** Keywords that describe a value without constraining it. */
const ANNOTATIONS = new Set([
  "$comment",
  "default",
  "deprecated",
  "description",
  "examples",
  "readOnly",
  "title",
  "writeOnly",
]);

/**
 * The schema with the annotations beside each `$ref` dropped. json-schema-to-typescript inlines a
 * `$ref` that has keywords beside it, so `{"$ref": JsonValue, "default": null}` would be typed as
 * an object rather than as `JsonValue`, any JSON at all. A constraint beside a `$ref` would be
 * inlined the same way, so it fails here instead, to be typed on purpose.
 */
export function bareRefs(schema: unknown, at = "#"): unknown {
  if (Array.isArray(schema)) {
    return schema.map((item, index) => bareRefs(item, `${at}/${index}`));
  }
  if (schema === null || typeof schema !== "object") {
    return schema;
  }
  if ("$ref" in schema) {
    const beside = Object.keys(schema).filter((key) => key !== "$ref" && !ANNOTATIONS.has(key));
    if (beside.length > 0) {
      throw new Error(
        `${at}: a $ref with ${beside.join(", ")} beside it would be typed as an object`,
      );
    }
    return { $ref: schema.$ref };
  }
  return Object.fromEntries(
    Object.entries(schema).map(([key, value]) => [key, bareRefs(value, `${at}/${key}`)]),
  );
}

/** The integrations as a constant, each read as it was declared: a key, a default, a sentence. */
function integrations(text: string): string {
  const declared = (JSON.parse(text) as { key: string; default: boolean; description: string }[])
    .map(
      ({ key, default: on, description }) =>
        `  ${JSON.stringify({ key, default: on, description })},\n`,
    )
    .join("");
  return (
    `${HEADER}// ${INTEGRATIONS}\n\n` +
    "/** lattice's integrations, in its registry's order: each key, its default, and what it is. */\n" +
    `export const INTEGRATIONS = [\n${declared}] as const;\n`
  );
}

/**
 * Every command's name, from the catalogs, as a constant and the union of its names, so a name
 * that is no command fails `tsc` (lattice RFC-0014).
 */
export function commands(catalogs: readonly string[]): string {
  const names = catalogs
    .flatMap((text) => Object.keys((JSON.parse(text) as { commands: object }).commands))
    .sort();
  return (
    `${HEADER}${CATALOGS.map((source) => `// ${source}\n`).join("")}\n` +
    "/** Every command of lattice's catalogs, by name, `<package>.<name>`, sorted. */\n" +
    `export const COMMANDS = [\n${names.map((name) => `  ${JSON.stringify(name)},\n`).join("")}] as const;\n\n` +
    "/** A command's name: one the catalogs declare, or `tsc` fails. */\n" +
    "export type CommandName = (typeof COMMANDS)[number];\n"
  );
}

/** Each REST surface's name in the client, by its generated file. */
const SURFACES: Readonly<Record<keyof typeof OPENAPI, string>> = {
  "artifactr.openapi.ts": "artifactr",
  "files.openapi.ts": "files",
  "diagrams.openapi.ts": "diagrams",
  "reflexr.openapi.ts": "reflexr",
  "grantr.openapi.ts": "grantr",
  "portalr.openapi.ts": "portalr",
  "relayr.openapi.ts": "relayr",
};

/** The methods an operation is called by. */
const METHODS = new Set(["get", "put", "post", "delete", "patch"]);

/**
 * What one operation's `x-lattice-command` says it calls, as a type: its command, the commands a
 * caller picks one of, `null` for one that calls none, or `"frames"` where its body carries
 * command frames, each named by its `type` (lattice ADR-0042).
 */
export function called(extension: unknown, at: string): string {
  if (typeof extension === "string") {
    return JSON.stringify(extension);
  }
  if (Array.isArray(extension) && extension.every((name) => typeof name === "string")) {
    return extension.map((name) => JSON.stringify(name)).join(" | ");
  }
  if (typeof extension === "object" && extension !== null && "frames" in extension) {
    return '"frames"';
  }
  if (typeof extension === "object" && extension !== null && "none" in extension) {
    return "null";
  }
  throw new Error(`${at}: x-lattice-command is ${JSON.stringify(extension)}`);
}

/** What each surface's operations call, by path and method, as one interface. */
export function calls(documents: Readonly<Record<string, unknown>>): string {
  const surfaces = Object.entries(documents).map(([surface, document]) => {
    const paths = (document as { paths: Record<string, Record<string, unknown>> }).paths;
    const entries = Object.entries(paths).map(([path, operations]) => {
      const methods = Object.entries(operations)
        .filter(([method]) => METHODS.has(method))
        .map(([method, operation]) => {
          const extension = (operation as Record<string, unknown>)["x-lattice-command"];
          return `${method}: ${called(extension, `${surface} ${method.toUpperCase()} ${path}`)};`;
        });
      return `    ${JSON.stringify(path)}: { ${methods.join(" ")} };\n`;
    });
    return `  ${surface}: {\n${entries.join("")}  };\n`;
  });
  return (
    `${HEADER}${Object.entries(OPENAPI)
      .map(([, source]) => `// ${source}\n`)
      .join("")}\n` +
    "/**\n" +
    " * What each operation calls, by surface, path and method, as its document's `x-lattice-command`\n" +
    " * names it: its command, the commands a caller picks one of, `null` for one that calls none, or\n" +
    ' * `"frames"` where its body carries command frames, each named by its `type` (lattice ADR-0042).\n' +
    " */\n" +
    `export interface Calls {\n${surfaces.join("")}}\n`
  );
}

/** The web packages whose requests `commands.used.json` lists, from the workspace's root. */
const SENDERS = ["client/src", "app/src", "admin/src", "ui/src"] as const;

/** Where `commands.used.json` is written: beside this package's `src`. */
export const USED = join(import.meta.dirname, "..", "commands.used.json");

/** A request, up to the path it is sent to: its command, as the request names it, is in between. */
const REQUEST = /\.(GET|PUT|POST|DELETE|PATCH)\(([^`"]*(?:"[^"/][^"]*"[^`"]*)*)[`"]\//g;

/** The commands a source file's requests name: a literal, or each of a conditional's. */
export function named(source: string, at: string): string[] {
  return [...source.matchAll(REQUEST)].flatMap(([request, , before = ""]) => {
    const names = [...before.matchAll(/"([a-z]+\.[a-z_]+)"/g)].map(([, name = ""]) => name);
    if (names.length === 0 && !/\bnull\b|"frames"/.test(before)) {
      throw new Error(`${at}: ${request.trim()} names no command with a literal`);
    }
    return names;
  });
}

/** Every command portalr's UIs send over REST, sorted, as `commands.used.json` lists them. */
export async function used(): Promise<string> {
  const web = join(import.meta.dirname, "..", "..");
  const names = new Set<string>();
  for (const sender of SENDERS) {
    const entries = await readdir(join(web, sender), { recursive: true });
    for (const entry of entries.sort()) {
      if (!/\.tsx?$/.test(entry) || /\.test\.tsx?$/.test(entry) || entry.startsWith("generated")) {
        continue;
      }
      const file = join(web, sender, entry);
      for (const name of named(await readFile(file, "utf8"), relative(web, file))) {
        names.add(name);
      }
    }
  }
  return `${JSON.stringify([...names].sort(), null, 2)}\n`;
}

/** Every generated file, by name, as it should read. */
export async function generate(): Promise<Record<string, string>> {
  const files: Record<string, string> = {};
  const documents: Record<string, unknown> = {};
  for (const [name, source] of Object.entries(OPENAPI) as [keyof typeof OPENAPI, string][]) {
    const document = JSON.parse(await readFile(join(root, source), "utf8"));
    files[name] = `${HEADER}// ${source}\n\n${astToString(await openapiTS(document))}`;
    documents[SURFACES[name]] = document;
  }
  files["calls.ts"] = calls(documents);
  for (const [name, source] of Object.entries(SCHEMAS)) {
    const schema = bareRefs(JSON.parse(await readFile(join(root, source), "utf8")));
    const types = await compile(schema as Parameters<typeof compile>[0], name.replace(".ts", ""), {
      bannerComment: "",
      additionalProperties: false,
      unreachableDefinitions: true,
      style: { printWidth: 100 },
    });
    files[name] = `${HEADER}// ${source}\n\n${types}`;
  }
  files["integrations.ts"] = integrations(await readFile(join(root, INTEGRATIONS), "utf8"));
  const catalogs = CATALOGS.map((source) => readFile(join(root, source), "utf8"));
  files["commands.ts"] = commands(await Promise.all(catalogs));
  return files;
}

/** The directory the files are written to. */
export const GENERATED = out;

if (import.meta.main) {
  for (const [name, text] of Object.entries(await generate())) {
    await writeFile(join(out, name), text);
  }
  await writeFile(USED, await used());
}
