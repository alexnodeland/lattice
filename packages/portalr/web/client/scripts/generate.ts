/**
 * Writes the client's types from the packages' committed documents: each REST surface's OpenAPI
 * document through openapi-typescript, and each WebSocket protocol's JSON Schema through
 * json-schema-to-typescript. The drift test calls `generate()` and compares; `moon run
 * client:types` writes. openapi-typescript loads TypeScript 6, this package's own `typescript`
 * (portalr ADR-0010).
 */

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(import.meta.dirname, "..", "..", "..", "..", "..");
const out = join(import.meta.dirname, "..", "src", "generated");

const HEADER =
  "// Generated by scripts/generate.ts from the committed document named below. Don't edit.\n";

const OPENAPI = {
  "artifactr.openapi.ts": "packages/artifactr/schemas/artifactr.openapi.json",
  "reflexr.openapi.ts": "packages/reflexr/schemas/reflexr.openapi.json",
  "grantr.openapi.ts": "packages/grantr/schemas/grantr.openapi.json",
  "portalr.openapi.ts": "packages/portalr/schemas/portalr.openapi.json",
} as const;

const SCHEMAS = {
  "artifactr.v1.ts": "packages/artifactr/schemas/artifactr.v1.json",
  "reflexr.v1.ts": "packages/reflexr/schemas/reflexr.v1.json",
  "reflexr.rules.v1.ts": "packages/reflexr/schemas/reflexr.rules.v1.json",
} as const;

/** Keywords that describe a value without constraining it. */
const ANNOTATIONS = new Set(["default", "description", "title", "examples"]);

/**
 * The schema with the annotations beside each `$ref` dropped. json-schema-to-typescript inlines a
 * `$ref` that has keywords beside it, so `{"$ref": JsonValue, "default": null}` would be typed as
 * an object rather than as `JsonValue`, any JSON at all.
 */
export function bareRefs(schema: unknown): unknown {
  if (Array.isArray(schema)) {
    return schema.map(bareRefs);
  }
  if (schema === null || typeof schema !== "object") {
    return schema;
  }
  const entries = Object.entries(schema);
  const annotatedRef =
    "$ref" in schema && entries.every(([key]) => key === "$ref" || ANNOTATIONS.has(key));
  return Object.fromEntries(
    entries
      .filter(([key]) => !(annotatedRef && key !== "$ref"))
      .map(([key, value]) => [key, bareRefs(value)]),
  );
}

/** Every generated file, by name, as it should read. */
export async function generate(): Promise<Record<string, string>> {
  const files: Record<string, string> = {};
  for (const [name, source] of Object.entries(OPENAPI)) {
    const document = JSON.parse(await readFile(join(root, source), "utf8"));
    files[name] = `${HEADER}// ${source}\n\n${astToString(await openapiTS(document))}`;
  }
  for (const [name, source] of Object.entries(SCHEMAS)) {
    const schema = bareRefs(JSON.parse(await readFile(join(root, source), "utf8")));
    const types = await compile(schema as Parameters<typeof compile>[0], name.replace(".ts", ""), {
      bannerComment: "",
      additionalProperties: false,
      unreachableDefinitions: true,
      style: { printWidth: 100 },
    });
    files[name] = `${HEADER}// ${source}\n\n${types}`;
  }
  return files;
}

/** The directory the files are written to. */
export const GENERATED = out;

if (import.meta.main) {
  for (const [name, text] of Object.entries(await generate())) {
    await writeFile(join(out, name), text);
  }
}
